-- Gym Management System V2 - PostgreSQL / Supabase Cloud
-- Base schema: six business tables from Requirements V2 + Data Dictionary.
-- Run ONCE on an empty Supabase project using SQL Editor.
-- Do not run SQL Server T-SQL scripts against Supabase.
-- Changes from V2: bcrypt hash embeds salt (no separate salt column),
-- case-insensitive username/email uniqueness, database-level overlap protection,
-- and RLS enabled for backend-only access.

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE public.member (
    member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    gender VARCHAR(20) NOT NULL,
    date_of_birth DATE NOT NULL,
    phone VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(100),
    address VARCHAR(255),
    training_objective VARCHAR(255),
    internal_note VARCHAR(1000),
    status VARCHAR(10) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Inactive')),
    CONSTRAINT ck_member_name_not_blank CHECK (btrim(full_name) <> ''),
    CONSTRAINT ck_member_phone_not_blank CHECK (btrim(phone) <> '')
);

CREATE UNIQUE INDEX uq_member_email_ci
    ON public.member (lower(email)) WHERE email IS NOT NULL;
CREATE INDEX idx_member_name_dob
    ON public.member (full_name, date_of_birth);

CREATE TABLE public.membership_plan (
    plan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    duration_months INTEGER NOT NULL CHECK (duration_months > 0),
    price NUMERIC(12,2) NOT NULL CHECK (price > 0),
    benefits VARCHAR(1000) NOT NULL,
    status VARCHAR(11) NOT NULL DEFAULT 'Available'
        CHECK (status IN ('Available', 'Unavailable')),
    CONSTRAINT ck_plan_name_not_blank CHECK (btrim(name) <> '')
);
CREATE UNIQUE INDEX uq_plan_name_ci ON public.membership_plan (lower(name));

CREATE TABLE public.membership (
    membership_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES public.member(member_id) ON DELETE RESTRICT,
    plan_id BIGINT NOT NULL REFERENCES public.membership_plan(plan_id) ON DELETE RESTRICT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    price_at_registration NUMERIC(12,2) NOT NULL CHECK (price_at_registration > 0),
    previous_membership_id BIGINT UNIQUE
        REFERENCES public.membership(membership_id) ON DELETE RESTRICT,
    CONSTRAINT ck_membership_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_membership_prev_not_self CHECK (
        previous_membership_id IS NULL OR previous_membership_id <> membership_id
    ),
    CONSTRAINT ex_membership_member_period EXCLUDE USING gist (
        member_id WITH =,
        daterange(start_date, end_date + 1, '[)') WITH &&
    )
);
CREATE INDEX idx_membership_member_end
    ON public.membership (member_id, end_date DESC);
CREATE INDEX idx_membership_end_date ON public.membership (end_date);

CREATE TABLE public.trainer (
    trainer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL,
    specialization VARCHAR(100),
    years_of_experience INTEGER CHECK (years_of_experience >= 0),
    status VARCHAR(10) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Inactive')),
    CONSTRAINT ck_trainer_name_not_blank CHECK (btrim(full_name) <> ''),
    CONSTRAINT ck_trainer_phone_not_blank CHECK (btrim(phone) <> '')
);
CREATE UNIQUE INDEX uq_trainer_email_ci ON public.trainer (lower(email));

CREATE TABLE public.training_session (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES public.member(member_id) ON DELETE RESTRICT,
    trainer_id BIGINT NOT NULL REFERENCES public.trainer(trainer_id) ON DELETE RESTRICT,
    session_date DATE NOT NULL,
    start_time TIME(0) NOT NULL,
    end_time TIME(0) NOT NULL,
    note VARCHAR(1000),
    status VARCHAR(10) NOT NULL DEFAULT 'Scheduled'
        CHECK (status IN ('Scheduled', 'Cancelled')),
    CONSTRAINT ck_session_hours CHECK (
        start_time >= TIME '05:00:00'
        AND end_time <= TIME '22:00:00'
        AND end_time > start_time
    ),
    CONSTRAINT ck_session_duration CHECK (
        end_time - start_time BETWEEN INTERVAL '30 minutes' AND INTERVAL '120 minutes'
    ),
    CONSTRAINT ex_session_trainer_no_overlap EXCLUDE USING gist (
        trainer_id WITH =,
        tsrange(session_date + start_time, session_date + end_time, '[)') WITH &&
    ) WHERE (status = 'Scheduled'),
    CONSTRAINT ex_session_member_no_overlap EXCLUDE USING gist (
        member_id WITH =,
        tsrange(session_date + start_time, session_date + end_time, '[)') WITH &&
    ) WHERE (status = 'Scheduled')
);
CREATE INDEX idx_session_trainer_date
    ON public.training_session (trainer_id, session_date);
CREATE INDEX idx_session_member_date
    ON public.training_session (member_id, session_date);

-- Authentication choice for initial implementation:
-- Spring Security owns username/password, while Supabase provides PostgreSQL/REST.
-- PasswordEncoder (e.g., bcrypt with {bcrypt} prefix) stores salt within hash.
CREATE TABLE public.account (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL
        CHECK (role IN ('Admin', 'Staff', 'Trainer', 'Member')),
    status VARCHAR(10) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Locked')),
    must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
    member_id BIGINT UNIQUE REFERENCES public.member(member_id) ON DELETE RESTRICT,
    trainer_id BIGINT UNIQUE REFERENCES public.trainer(trainer_id) ON DELETE RESTRICT,
    CONSTRAINT ck_account_profile CHECK (
        (role = 'Member' AND member_id IS NOT NULL AND trainer_id IS NULL)
        OR (role = 'Trainer' AND trainer_id IS NOT NULL AND member_id IS NULL)
        OR (role IN ('Admin', 'Staff') AND member_id IS NULL AND trainer_id IS NULL)
    ),
    CONSTRAINT ck_account_username_not_blank CHECK (btrim(username) <> '')
);
CREATE UNIQUE INDEX uq_account_username_ci ON public.account (lower(username));
CREATE INDEX idx_account_role_status ON public.account (role, status);

